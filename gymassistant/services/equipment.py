"""
Снаряд упражнения и шаг веса.

Шаг «±2.5 кг» стоял в интерфейсе константой, одинаковой для всего: и для приседа,
где 2.5 — это 2 % рабочего веса, и для махов гантелями на 8 кг, где это 31 %, и для
блока, где вес вообще набирается не килограммами. То есть кнопки предлагали то,
чего в зале нет.

Задаёт всё это не упражнение, а СНАРЯД: гриф с блинами 1.25 ходит по 2.5, ряд
гантелей — по 2, блок — по одному блоку. Поэтому полем стал снаряд, а остальное
считается из него. У пресетов каталога снаряд проставлен нами (seed.py), а не
пользователем: по названию он очевиден, а лишний вопрос на пути к первой
тренировке дороже точности.

Модуль чистый: ни FastAPI, ни ORM. Только снаряд → число.
"""

BARBELL = "barbell"
DUMBBELL = "dumbbell"
STACK = "stack"
MACHINE = "machine"
BODYWEIGHT = "bodyweight"
OTHER = "other"

EQUIPMENT = (BARBELL, DUMBBELL, STACK, MACHINE, BODYWEIGHT, OTHER)

# Сколько килограммов в одном щелчке кнопки.
#
# Для штанги, гантелей и тренажёра это шаг: на сколько подвинуть вес. Выбран
# по асимметрии ошибки — промах в мелкую сторону стоит лишнего тапа, промах
# в крупную делает вес НЕДОСТИЖИМЫМ (с шагом 5 от 35 не попасть в 37.5).
#
# Для блока то же число значит другое: сколько весит ОДИН БЛОК. Считать блок
# в килограммах нельзя вовсе — у разных станков они разные, а человек у станка
# оперирует не весом, а номером блока, куда воткнут пин. Поэтому там кнопки ходят
# по одному блоку, а килограммы — производная, нужная только объёму и рекордам.
# Ошибиться в весе блока не страшно: их количество, то есть то, что человек
# воспроизводит в зале, остаётся точным.
#
# Настоящие числа всё равно зависят от зала — блок по 4.5, гантельный ряд через
# 2.5, старый тренажёр через 7. Для этого есть `Exercise.weight_step`: снаряд
# задаёт разумное начало, а не приговор.
HARDWARE_STEP = {
    BARBELL: 2.5,    # два блина по 1.25 — самые мелкие в обычном зале
    DUMBBELL: 2.0,   # шаг гантельного ряда
    STACK: 5.0,      # вес одного блока, а не шаг в килограммах
    MACHINE: 2.5,    # тренажёр грузят обычными блинами
}

# Снаряд неизвестен (своё упражнение, у которого не спросили) — берём шаг штанги
# как самый частый. Врать он может только в меньшую сторону, а это безопаснее.
DEFAULT_STEP = 2.5

# Человеческие названия — их же показывает форма своего упражнения.
TITLES = {
    BARBELL: "Штанга",
    DUMBBELL: "Гантели",
    STACK: "Блок",
    MACHINE: "Тренажёр",
    BODYWEIGHT: "Свой вес",
    OTHER: "Другое",
}


def is_known(equipment: str | None) -> bool:
    return equipment in EQUIPMENT


def counts_blocks(equipment: str | None) -> bool:
    """
    Считается ли нагрузка блоками, а не килограммами.

    Блок — единственный снаряд, где человек не знает и не выбирает вес: он
    переставляет пин на нужный блок. У разных станков они разные, поэтому «шаг
    в килограммах» здесь неправильная единица в принципе — любое число будет
    верным для одного зала и мимо для соседнего.
    """
    return equipment == STACK


def is_bodyweight(equipment: str | None) -> bool:
    """
    Свой вес — подтягивания, брусья, планка.

    Это НЕ «веса не бывает»: подтягивания и брусья сплошь и рядом делают с поясом.
    Значит только одно — вес не обязателен, и по умолчанию его не спрашивают.
    """
    return equipment == BODYWEIGHT


def weight_step(equipment: str | None, override: float | None = None) -> float:
    """
    Сколько килограммов в одном щелчке кнопки: шаг веса, а у блока — вес блока.

    `override` — `Exercise.weight_step`, поправка на конкретный зал. Ноль и
    отрицательное читаем как «нет поправки»: так клиент её снимает, не имея
    способа прислать NULL через PATCH.

    У своего веса число тоже есть — блины на пояс вешают такие же, как на штангу.
    Раньше здесь возвращался None, и клиент по нему решал, показывать ли поле веса
    вообще; теперь про это отвечает `is_bodyweight`, а число остаётся всегда.

    Неизвестный снаряд (строка из старой базы) ведёт себя как OTHER, а не падает:
    снаряд — подсказка интерфейсу, а не инвариант.
    """
    if override and override > 0:
        return float(override)
    return HARDWARE_STEP.get(equipment, DEFAULT_STEP)
