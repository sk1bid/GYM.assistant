BY_ID = {template.id: template for template in TEMPLATES}


def template_json(template: ProgramTemplate) -> dict:
    """Что видит экран выбора: чем эта программа отличается от соседней."""
    return {
        "id": template.id,
        "name": template.name,
        "subtitle": template.subtitle,
        "days": template.days_count,
        # Показываем состав, а не только число дней: выбирают ведь по нему.
        "preview": [
            {"day_of_week": day, "exercises": list(names)}
            for day, names in template.days.items()
        ],
    }
