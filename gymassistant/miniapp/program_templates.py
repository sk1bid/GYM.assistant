"""
Готовые программы — лекарство от пустого холста.

Новая программа заводила семь дней «отдых» и оставляла человека наедине с ними.
Тому, кто уже знает, что такое сплит, это в самый раз; новичок же на этом экране
и останавливается — он не знает не только какие упражнения выбрать, но и сколько
дней в неделю ходить. Править готовое умеют все, сочинять с нуля — далеко не все,
поэтому шаблон создаётся сразу заполненным, а дальше становится обычной программой:
дни правятся, упражнения добавляются и убираются, ничем от собранной руками она
не отличается.

Шаблон — это только НАЗВАНИЯ упражнений из каталога пресетов. Не id: каталог
наполняется `seed.py` при старте, id зависят от порядка вставки в конкретной базе,
и зашитые числа разъехались бы между прод- и тест-контуром. Имени, которого в
каталоге не нашлось, шаблон молча не заметит — программа создастся без него,
а не упадёт на ровном месте.

Дни недели выбраны с отдыхом между тренировками (Пн/Ср/Пт, Пн/Вт/Чт/Пт) — это
самая частая раскладка, и она же самая безобидная: расписание всё равно правится
одним движением, а вот стартовать с семи подряд заполненных дней было бы вредным
советом.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class ProgramTemplate:
    id: str
    name: str
    subtitle: str
    # день недели → упражнения в порядке выполнения
    days: dict[str, tuple[str, ...]]

    @property
    def days_count(self) -> int:
        return len(self.days)


